def gh_json(path):
    """GET one GitHub API path. Raises on any failure; callers decide."""
    import urllib.request
    req = urllib.request.Request(
        f"https://api.github.com/{path}",
        headers={"Accept": "application/vnd.github+json",
                 "User-Agent": "burrow-site-release"})
    with urllib.request.urlopen(req, timeout=20) as r:
        return json.loads(r.read().decode("utf-8"))


def fetch_stars():
    """Stargazer count, or None when GitHub isn't reachable."""
    try:
        return gh_json("repos/caezium/Burrow")["stargazers_count"]
    except Exception as e:                                  # noqa: BLE001
        print(f"star count: skipped ({e})", file=sys.stderr)
        return None


def compact(n):
    """1234 -> 1.2k, matching how repo badges render large counts."""
    if n < 1000:
        return str(n)
    if n < 10000:
        return f"{n / 1000:.1f}k".replace(".0k", "k")
    return f"{round(n / 1000)}k"


def fetch_download_total():
    """Sum every release asset's download count. None when GitHub isn't
    reachable, the caller then leaves the existing number alone."""
    total, page = 0, 1
    try:
        while True:
            batch = gh_json(f"repos/caezium/Burrow/releases?per_page=100&page={page}")
            if not batch:
                break
            for release in batch:
                for asset in release.get("assets", []):
                    total += asset.get("download_count", 0)
            if len(batch) < 100:
                break
            page += 1
    except Exception as e:                                  # noqa: BLE001
        print(f"download count: skipped ({e})", file=sys.stderr)
        return None
    return total


