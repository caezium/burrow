def breadcrumb_ld(trail):
    """trail: [(name, url), ...] ending at the current page."""
    return json.dumps({
        "@context": "https://schema.org", "@type": "BreadcrumbList",
        "itemListElement": [
            {"@type": "ListItem", "position": i + 1, "name": n, "item": u}
            for i, (n, u) in enumerate(trail)
        ],
    }, separators=(",", ":"))


# Languages the site is published in. scripts/site-i18n.py renders the copies
# under docs/<lang>/; this script owns the English pages, so it renders their
# picker and alternates itself. Keep the two lists in step — docs/localization.md.
SITE_LANGUAGES = {
    "zh-Hans": "简体中文", "zh-Hant": "繁體中文", "ru": "Русский",
    "ja": "日本語", "de": "Deutsch", "fr": "Français",
    "es": "Español", "ko": "한국어", "pt-BR": "Português (Brasil)",
}


def lang_picker(page_path):
    """The English page's language menu, marked so site-i18n.py can swap it."""
    items = [f'<a href="/{page_path}" hreflang="en" aria-current="page">English</a>']
    items += [f'<a href="/{code}/{page_path}" hreflang="{code}">{name}</a>'
              for code, name in SITE_LANGUAGES.items()]
    return ('<!-- LANGPICK:BEGIN --><details class="langpick">'
            '<summary aria-label="Language"><span>English</span></summary>'
            f'<nav>{"".join(items)}</nav></details><!-- LANGPICK:END -->')


def lang_alternates(page_path):
    """hreflang links pairing the English page with its translated copies."""
    rows = [f'<link rel="alternate" hreflang="x-default" href="{SITE}/{page_path}">',
            f'<link rel="alternate" hreflang="en" href="{SITE}/{page_path}">']
    rows += [f'<link rel="alternate" hreflang="{code}" href="{SITE}/{code}/{page_path}">'
             for code in SITE_LANGUAGES]
    return "\n".join(rows)

def render_sitemap(posts):
    today = max(p["date"] for p in posts)
    urls = [(f"{SITE}/", "1.0", today), (f"{SITE}/install", "0.9", today),
            (f"{SITE}/docs", "0.9", today),
            (f"{SITE}/compare", "0.8", today), (f"{SITE}/blog/", "0.8", today),
            (f"{SITE}/releases", "0.6", today), (f"{SITE}/roadmap", "0.6", today)]
    urls += [(post_url(p), "0.7", p["date"]) for p in posts]
    # Every translated copy, a notch below its English original. The language
    # list is duplicated from site-i18n.py rather than imported: this script is
    # the one that must keep running if that one is ever dropped.
    for code in ("zh-Hans", "zh-Hant", "ru", "ja", "de", "fr", "es", "ko", "pt-BR"):
        for path, pr in (("", "0.9"), ("docs", "0.8"), ("compare", "0.7"),
                         ("releases", "0.5"), ("roadmap", "0.5")):
            urls.append((f"{SITE}/{code}/{path}", pr, today))
    body = "\n".join(f'  <url><loc>{u}</loc><lastmod>{d}</lastmod>'
                      f'<priority>{pr}</priority></url>' for u, pr, d in urls)
    return ('<?xml version="1.0" encoding="UTF-8"?>\n'
            '<urlset xmlns="http://www.sitemaps.org/schemas/sitemap/0.9">\n'
            f'{body}\n</urlset>\n')


def main():
    ap = argparse.ArgumentParser()
    ap.add_argument("--check", action="store_true",
                    help="verify generated files are up to date; exit 1 if not")
    ap.add_argument("--list-icons", action="store_true")
    ap.add_argument("--stats", "--downloads", dest="stats", action="store_true",
                    help="also refresh the download + star counts from the GitHub "
                         "API (needs network; left alone otherwise)")
    args = ap.parse_args()

    if args.list_icons:
        print("icons: ", ", ".join(sorted(ICONS)))
        print("colors:", ", ".join(sorted(COLORS)))
        return

    releases = json.loads(DATA.read_text(encoding="utf-8"))["releases"]
    if not releases:
        sys.exit("releases.json: no releases")
    for r in releases:
        validate(r)
    versions = [r["version"] for r in releases]
    if sorted(versions, key=lambda v: [int(p) for p in v.split(".")], reverse=True) != versions:
        sys.exit("releases.json: releases must be ordered newest first")

    roadmap = json.loads(ROADMAP.read_text(encoding="utf-8"))
    validate_roadmap(roadmap)

    stats = json.loads(STATS.read_text(encoding="utf-8"))
    if args.stats:
        dl, st = fetch_download_total(), fetch_stars()
        if dl is not None:
            stats["downloads"] = dl
        if st is not None:
            stats["stars"] = st
        STATS.write_text(json.dumps(stats, indent=2) + "\n", encoding="utf-8")
    stars = stats["stars"]

    compare = json.loads(COMPARE.read_text(encoding="utf-8"))
    blog = json.loads(BLOG_JSON.read_text(encoding="utf-8"))
    blog_posts = sorted(blog["posts"], key=lambda x: x["date"], reverse=True)
    BLOG_DIR.mkdir(exist_ok=True)

    targets = {
        INDEX: patch_index(INDEX.read_text(encoding="utf-8"), releases[0], stats),
        INSTALL_HTML: render_install(releases[0]["version"], stats["downloads"], stars),
        COMPARE_HTML: render_compare(compare, stars),
        DOCS_HTML: render_docs(json.loads(DOCS_JSON.read_text(encoding="utf-8")), stars),
        BLOG_INDEX: render_blog_index(blog, stars),
        SITEMAP: render_sitemap(blog_posts),
        ROBOTS: render_robots(),
        CHROME_CSS_FILE: CHROME_CSS,
        HISTORY: render_history(releases, stars),
        ROADMAP_HTML: render_roadmap(roadmap, stars),
        README: patch_readme(README.read_text(encoding="utf-8"), roadmap),
    }
    for post in blog_posts:
        targets[BLOG_DIR / f'{post["slug"]}.html'] = render_blog_post(
            post, blog["categories"], blog_posts, stars)

    stale = [str(p.relative_to(ROOT)) for p, new in targets.items()
             if not p.exists() or p.read_text(encoding="utf-8") != new]

    if args.check:
        if stale:
            sys.exit(f"out of sync with docs JSON: {', '.join(stale)} "
                     f",  run python3 scripts/site-release.py and commit the result")
        print("site content is in sync")
        return

    for p, new in targets.items():
        p.write_text(new, encoding="utf-8")
    print(f"regenerated: {', '.join(stale) if stale else 'nothing changed'}")


if __name__ == "__main__":
    main()
